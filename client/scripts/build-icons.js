const { icons } = JSON.parse(readFileSync(new URL('../../node_modules/@iconify-json/game-icons/icons.json', import.meta.url)));
const lines = Object.entries(ICONS).map(([name, entry]) => {
  if (entry.d) return `  ${name}: { d: '${entry.d}' },`;
  if (entry.line) return `  ${name}: { line: '${entry.line}' },`;
  const [source, rotate] = [entry].flat();
  const d = /^<path fill="currentColor" d="([^"]+)"\/>$/.exec(icons[source]?.body ?? '')?.[1];
  if (!d) throw new Error(`No single-path icon named ${source}`);
  return `  ${name}: { d: '${d}'${rotate ? `, rotate: ${rotate}` : ''} },`;
});
const out = `// Generated by scripts/build-icons.js. Don't edit by hand.
// Icons by Lorc, Delapouite and contributors, from https://game-icons.net (CC BY 3.0).
export const ICON_PATHS = {
${lines.join('\n')}
};
`;
writeFileSync(fileURLToPath(new URL('../src/components/iconPaths.js', import.meta.url)), out);
console.log(`Wrote ${lines.length} icons.`);
